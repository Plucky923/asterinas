"""Assemble the real Host gates and regenerate relocation-resolved audit fixtures.

Requires GNU as, ld, nm and objcopy. Intermediates stay in target/. This uses
dummy Rust call destinations only; all audited instructions come from source.
"""

from pathlib import Path
import re
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]


def run(*args):
    return subprocess.check_output(args, text=True)


def main():
    cache = ROOT / "osdk/target/host-audit-fixtures"
    cache.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix="gates-", dir=cache) as directory:
        work = Path(directory)
        host = (ROOT / "ostd/src/kernelet/host_run.S").read_text()
        operands = dict(stack_pool_start=64, stack_pool_end=72, stack_pool_live=80,
                        stop_state=344, stack_stride=524288, stack_bytes=262144,
                        stack_reserve=65536, phase_starting=8, phase_image=1,
                        phase_entering=2, phase_returning=4,
                        stop_requested=2147483648, rq1_bench=1, rq1_stack_check_mode=1)
        for key, value in operands.items():
            host = host.replace("{" + key + "}", str(value))
        (work / "host.S").write_text(host)
        trap = (ROOT / "ostd/src/arch/x86/trap/trap.S").read_text()
        trap = trap.replace("{kernelet_host}", "1").replace(".rodata", ".section .rodata")
        (work / "trap.S").write_text(".intel_syntax noprefix\n" + trap)
        targets = set(re.findall(r"kernelet_host_\w+_impl", host))
        targets.add("trap_handler")
        targets.add("trap_syscall_entry")
        targets.add("kernelet_host_recovery_stack_impl")
        (work / "dummy.S").write_text(".text\n" + "\n".join(
            f".global {name}\n{name}:\nret\n" for name in sorted(targets)))
        for name in ("host", "trap", "dummy"):
            run("as", "--64", "--keep-locals", "-o", str(work / (name + ".o")), str(work / (name + ".S")))
        (work / "link.ld").write_text("""
SECTIONS { . = 0x10000; .text : { *(.text) } .rodata : { *(.rodata*) } }
__cpu_local_start = 0x600000;
KERNELET_HOST_STATE_PTR = 0x700000;
KERNELET_IRQ_STACK_TOP = 0x700008;
KERNELET_IRQ_STACK_BUSY = 0x700010;
""")
        elf = work / "gates.elf"
        run("ld", "--discard-none", "-T", str(work / "link.ld"), "-o", str(elf),
            *(str(work / (name + ".o")) for name in ("host", "trap", "dummy")))
        symbols = {}
        sizes = {}
        for line in run("nm", "-anS", str(elf)).splitlines():
            fields = line.split()
            if len(fields) == 4:
                address, size, _, name = fields
                sizes[name] = int(size, 16)
            elif len(fields) == 3:
                address, _, name = fields
            else:
                continue
            symbols[name] = int(address, 16)
        raw = work / "text.bin"
        run("objcopy", "-O", "binary", "--only-section=.text", str(elf), str(raw))
        text = raw.read_bytes()
        out = ["// SPDX-License-Identifier: MPL-2.0\n",
               "// Generated by tools/regenerate_kernelet_host_audit.py.\n"]
        used = set(re.findall(r"\b[A-Z][A-Z0-9_]*\b",
            (ROOT / "osdk/src/kernelet/host_audit.rs").read_text()))
        selected = {
            "SHARED_NEAR": ("kernelet_service_log_write", None),
            "SHARED_SHORT_JUMP": ("kernelet_service_buffer", None),
            "BOUNDED": ("kernelet_service_vcpu_on_spin", None),
            "ECHO": ("kernelet_service_rq1_echo", None),
            "BOUNDED_RETURN": ("kernelet_service_bounded_return", None),
            "STOP": ("kernelet_service_stop", None),
            "SERVICE_RETURN": (".Lservice_return", ".Lservice_return_end"),
            "NATIVE_TRAP": ("_trap_from_kernel", "kernelet_kernel_trap_end"),
        }
        for label, (name, end) in selected.items():
            start = symbols[name]
            size = symbols[end] - start if end else sizes[name]
            data = text[start - 0x10000:start - 0x10000 + size]
            if label + "_ADDRESS" in used:
                out.append(f"pub(super) const {label}_ADDRESS: u64 = {start:#x};\n")
            if label not in used:
                continue
            out.append(f"pub(super) const {label}: &[u8] = &[\n")
            for offset in range(0, len(data), 16):
                out.append("    " + ", ".join(f"0x{b:02x}" for b in data[offset:offset + 16]) + ",\n")
            out.append("];\n")
        for name in sorted(symbols):
            if name in targets or name.endswith("_budget") or name.startswith("kernelet_rq1_stack_check_") or name in (
                "kernelet_host_exit", ".Linvalid_stack", ".Linvalid_service"):
                label = name.upper().replace(".", "")
                if label in used:
                    out.append(f"pub(super) const {label}: u64 = {symbols[name]:#x};\n")
        dest = ROOT / "osdk/src/kernelet/host_audit/fixtures.rs"
        dest.parent.mkdir(exist_ok=True)
        dest.write_text("".join(out))


if __name__ == "__main__":
    main()
